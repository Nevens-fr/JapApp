/**
 * Types for the pedagogical engine
 * Lot 3: Pedagogical engine
 */

/**
 * Knowledge state for a user concept
 */
export type KnowledgeState = 
  | "not_discovered"    // The concept has not been introduced yet
  | "introduced"        // The concept has been presented
  | "learning"          // The user is learning this concept
  | "review"            // The concept needs to be reviewed
  | "mastered";         // The concept is considered mastered

/**
 * Mastery level of a concept
 * Value between 0.0 (discovery) and 1.0 (complete mastery)
 */
export interface MasteryLevel {
  value: number;           // 0.0 to 1.0 (Global mastery score)
  state: KnowledgeState;
  lastReviewedAt: Date | null;
  nextReviewAt: Date | null;
  
  // Spaced Repetition System (SRS) fields (SM-2)
  easinessFactor: number;  // EF factor (default 2.5), adjusts based on performance
  intervalDays: number;    // Current interval in days (0 for new, increases with success)
  repetitionCount: number; // Number of successful repetitions in a row
  
  // Statistics
  correctCount: number;
  incorrectCount: number;
  totalAttempts: number;
}

/**
 * Exercise result
 */
export interface ExerciseResult {
  exerciseId: string;
  isCorrect: boolean;
  attempts: number;
  timeSpentMs: number;
  timestamp: Date;
}

/**
 * Lesson state
 */
export interface LessonState {
  lessonId: string;
  status: "not_started" | "in_progress" | "completed" | "abandoned";
  results: ExerciseResult[];
  startedAt: Date | null;
  completedAt: Date | null;
  score: number | null; // Success percentage (0-100)
}

/**
 * Pedagogical event generated by user action
 */
export interface PedagogicalEvent {
  type: 
    | "lesson_started"
    | "lesson_completed"
    | "lesson_abandoned"
    | "exercise_answered"
    | "knowledge_updated"
    | "review_scheduled"
    | "mastery_changed";
  timestamp: Date;
  data: Record<string, unknown>;
}

/**
 * Pedagogical engine configuration
 */
export interface LearningEngineConfig {
  // Mastery threshold to consider a concept as mastered
  masteryThreshold: number;
  // Minimum number of correct answers to validate a concept
  minCorrectAnswers: number;
  // Decay factor for spaced repetition
  reviewDecayFactor: number;
  // Maximum number of attempts per exercise
  maxAttemptsPerExercise: number;
  
  // SRS Defaults
  initialEasinessFactor: number;
  initialIntervalDays: number;
}

/**
 * Default engine configuration
 */
export const DEFAULT_CONFIG: LearningEngineConfig = {
  masteryThreshold: 0.8,
  minCorrectAnswers: 3,
  reviewDecayFactor: 1.5,
  maxAttemptsPerExercise: 3,
  initialEasinessFactor: 2.5,
  initialIntervalDays: 0,
};

// ============================================================
// Types for Lot 5 integration
// ============================================================

/**
 * Pedagogical concept (vocabulary, kana, kanji, grammar)
 */
export interface Concept {
  id: string;
  name: string;
  type: "vocab" | "kana" | "kanji" | "grammar";
  description: string;
  difficulty: number;
  prerequisites: string[];
}

/**
 * Lesson step
 */
export interface LessonStep {
  id: string;
  type: "presentation" | "explanation" | "example" | "exercise" | "check" | "synthesis";
  content: {
    title: string;
    body: string;
    japanese?: string;
    reading?: string;
    meaning?: string;
  };
  exerciseId?: string;
}

/**
 * Structured lesson
 */
export interface Lesson {
  id: string;
  title: string;
  description: string;
  conceptId: string;
  type?: "vocab" | "kana" | "kanji" | "grammar";
  steps?: LessonStep[];
  lessonSteps?: LessonStep[]; // Lot 7.1: Steps pédagogiques structurées
  exercises?: string[];
  estimatedDuration?: number;
}

/**
 * Lesson progress
 */
export interface LessonProgress {
  status: "not_started" | "in_progress" | "completed" | "abandoned";
  currentStep: number;
  score: number | null;
}
